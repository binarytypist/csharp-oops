namespace Bakery.Utilities.Enums
{
    // Enumeration representing the types of drinks available in the bakery menu.
    // The DrinkType enum defines two values: Tea and Water, which correspond to the types of drink items that can be added to the bakery menu.
    // The DrinkType enum is used to specify the type of drink when adding a new drink item to the bakery menu, allowing for clear and consistent
    // identification of the drink type in the application.
    public enum DrinkType
    {
        Tea = 1,
        Water = 2
    }
}
